#!/bin/sh
# fan_minduty_sweep.sh —— 找「能自启动 + 安静」的最低占空比
#
# ============================================================================
# 【为什么这一步必须有人听，不能全自动】
# ============================================================================
# 这块板的风扇只有一根 PWM 出脚（AA11），**没有转速反馈（tach）**。
# 所以"风扇到底还转不转"在电气上是测不到的。
#
# 温度也当不了替代判据：实测把风扇完全停转、四个 CPU 满载、PL 密码核循环跑，
# 180 秒结温也只从 34.1 升到 36.5°C。停转与不停转在温度上几乎看不出差别。
#
# 于是判据只能是人的耳朵/眼睛。这个脚本负责把「人要做的事」压到最小：
# 它按档扫一遍，每档都念出来，人只需要记住"哪一档起不来 / 开始嗡嗡响"。
#
# ============================================================================
# 【为什么每档都先停 3 秒】
# ============================================================================
# 直流风扇有两个不同的阈值：
#   ① **自启动**阈值 —— 从静止能转起来所需的最低占空比；
#   ② **维持**阈值   —— 已经在转时能继续转的最低占空比（比 ① 低）。
# 没有转速反馈时，能固化进 RTL 的只能是 ①。因为若取 ②，风扇一旦因为任何原因
# 停住（掉电瞬间、卡顿、积灰），就再也起不来，而**没有任何人会发现**。
# 所以每档先给 0% 停 3 秒，再给候选值 —— 测的是 ①。
#
# 用法：
#   sh fan_minduty_sweep.sh                 # 默认档位表 25..8
#   sh fan_minduty_sweep.sh 7 6 5 4 3 2 1   # 自己指定要试的档位
#   REPEAT=3 sh fan_minduty_sweep.sh 6      # 同一档反复起停 3 次（确认可靠性）
#   HOLD=180 sh fan_minduty_sweep.sh 12     # 起转后持续跑 180 秒（确认不会跑着跑着停）
#
# HOLD 是必要的一步：起转成功 ≠ 能一直转。低占空比下风扇可能转几十秒后
# 因为负载不均/轴承阻力停住。所以定下候选值后要持续跑几分钟再确认一次。
#
# ⚠️ 「能起来」和「每次都能起来」是两回事。定下候选值之后，务必用 REPEAT=5
#    再确认一遍 —— 自启动在临界点附近是概率性的，单次成功说明不了问题。
#
# 中断：  Ctrl-C 也会恢复自动调速（有 trap）
# ============================================================================
OVR=0x8005000C     # [0]=覆盖使能 [15:8]=占空比 0..100
STAT=0x80050004    # [15:0]=温度码 [23:16]=占空比 [26:24]=档位

set_duty() { busybox devmem $OVR w $(printf '0x%02x01' "$1"); }
auto()     { busybox devmem $OVR w 0x0; }

# 任何退出路径都要回到自动调速 —— 绝不能把风扇留在手动低速上走人
trap 'echo; echo "中断 —— 恢复自动调速"; auto; exit 130' INT TERM HUP

LIST="$*"
[ -z "$LIST" ] && LIST="25 20 18 16 14 12 10 8"
N="${REPEAT:-1}"

echo "=== 最低占空比扫描 ==="
echo "档位表：$LIST    每档试 $N 次"
echo "每次：先停 3 秒（等风扇彻底停下）→ 再给该占空比 4 秒"
echo "请注意听：**这一档能不能从静止转起来**、有没有嗡嗡异响"
echo

for D in $LIST; do
    i=1
    while [ "$i" -le "$N" ]; do
        set_duty 0
        sleep 3
        if [ "$N" -gt 1 ]; then
            echo "  >>> ${D}%   第 $i/$N 次 —— 听 4 秒（起来了吗？）"
        else
            echo "  >>> ${D}%   —— 听 4 秒（能起来吗？响吗？）"
        fi
        set_duty "$D"
        sleep 4
        i=$((i+1))
    done
    if [ -n "$HOLD" ]; then
        echo "      持续跑 ${HOLD} 秒 —— 结束时请确认它**还在转**"
        t=0
        while [ "$t" -lt "$HOLD" ]; do
            sleep 10
            t=$((t+10))
            echo "        ${t}s / ${HOLD}s   温度码=$(busybox devmem $STAT)"
        done
    fi
done

auto
echo
echo "扫描结束，已恢复自动调速。"
echo -n "OVR 回读（应为 0x00000000）= "; busybox devmem $OVR
echo -n "STATUS = "; busybox devmem $STAT
