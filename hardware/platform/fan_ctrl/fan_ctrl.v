// fan_ctrl —— 按结温调速的风扇控制器（AXU3EGB，PWM 出到 AA11）
//
// 出厂设计把风扇直接拉成常转满速，噪音很大。这个模块读 ZynqMP 的片上温度，
// 按档位给 PWM，低温安静、高温跟上。
//
// ============================================================================
// 【为什么温度必须从 PL 的 SYSMONE4 读，而不是让 Linux 读了写寄存器】
// ============================================================================
// 风扇是**散热**，不是外设：它必须在没有 Linux 的时候也工作 —— 开机那几十秒、
// U-Boot 里停着的时候、内核挂死的时候、以及任何"软件本该更新占空比却没更新"
// 的时刻。把温度源放在 PS 侧，等于让散热依赖软件活着。
//
// 所以温度直接从 PL 的系统监测单元（UltraScale+ 的 SYSMONE4）经 DRP 读，
// 整条链路只依赖 PL 时钟。AXI 那一路（fan_ctrl_axi）**只是观测口**，
// 拔掉它风扇照样正常工作。
//
// ============================================================================
// 【AA11 是低有效：低=转，高=停】
// ============================================================================
// 所以"占空比 D"对应的是**引脚为低的时间占 D**。这一点写反了的后果是
// 温度越高越安静 —— 而且在实验室里未必立刻看出来，等看出来时芯片已经烤过了。
// 下面的 `fan_pin = ~pwm_on` 是唯一一处反相，别在别处再反一次。
//
// ============================================================================
// 【阈值用 ADC 码，不用摄氏度】
// ============================================================================
// UltraScale+ 的换算是 T(°C) = code/65536 × 502.9098127 − 273.8195117。
// 在 RTL 里做这个换算要除法和小数；反过来把每个档位的摄氏度**在生成时**
// 反算成整数 ADC 码，RTL 里就只剩比较大小。
//     code = (T + 273.8195117) × 65536 / 502.9098127
// 下面每个常数后面都标了它对应的摄氏度，改的时候按注释改，别直接改数字。
//
// ============================================================================
// 【三道安全，方向永远是「多吹」】
// ============================================================================
//  ① 最低档不是 0% 而是 DUTY_QUIET —— ZU3EG 满载发热大，把风扇停死不是省电
//     而是赌运气。**风扇任何时候都在转**，这一条没有变。
//
//     DUTY_QUIET 从 25% 降到 8%（2026-08 实测定的，过程见下面「8% 凭什么」）。
//
// ============================================================================
// 【8% 凭什么 —— 这块板没有转速反馈，所以这个数是量出来的不是猜的】
// ============================================================================
// 风扇只有一根 PWM 出脚（AA11），**没有 tach**，所以"还转不转"电气上测不到。
// 用 AXI 的覆盖寄存器（OVR）在真板上逐档试、人耳判定，得到：
//     **维持下限 ≈ 6%**（5% 维持不住，6%/8% 反复试 3/3 次都能继续转）。
//
// ⚠️ 上面那个 6% 是**维持阈值**，不是自启动阈值 —— 第一版测法给的停转窗口
//    只有 3 秒，风扇靠惯性还在转，量到的是"还在转时能不能维持"。
//    把维持阈值当自启动阈值用，会以为有余量其实没有。这个坑踩过一次，留在
//    这里当记录：**测自启动必须先确认风扇完全静止**。
//
// 用 STOP=20（停转窗口 20 秒、亲眼确认完全静止）重测：
//     **8% 能从静止自启动**。
// 再用 HOLD=180 连跑 3 分钟：
//     **8% 能一直转**，不会起来之后又被轴承阻力停住。
// 所以 8% 三项都过：维持、自启动、持续。全是量出来的，不是推出来的。
//
// 取 8% 而不是 6%，理由是**正常运行里根本用不到自启动**：
//   · 上电时复位值是满速（等第一个有效温度），风扇必定已经转起来；
//   · 之后降到 8% 是从 25% 那一档降下来的 —— 那时它已经在转。
// 所以 8% 只需要满足**维持**阈值，而维持阈值比自启动阈值低得多。
//
// 残余风险只有「跑着被外力卡停、需要自己重新起来」。三重兜底：
//   · **实测 8% 能从静止自启动**（STOP=20 的重测，见上）；
//   · 老化后万一起不来 —— 温度一升，档位机推到 25%/40%，那个力度必然带得动
//     （也就是说下面的第 ① 条温度环**顺带就是停转自愈**）；
//   · 这块板风扇**完全停转 + 四核满载 + PL 密码核循环**，180 秒结温也只从
//     34.1 升到 36.5°C —— 停转本身在这块板上不构成热风险。
//
//     ⚠️ 最后这条是**这块板**的实测结论，不是通用结论。换风扇、换散热片、
//        换到通风更差的机箱里，都要重新量一遍再定这个数。
//
// ============================================================================
// 【换风扇之后怎么重新定这个数】
// ============================================================================
// board/scripts/fan_minduty_sweep.sh 把这次的测法固化下来了：
//     STOP=20 sh fan_minduty_sweep.sh 8 10 12 ...   # 自启动（必须完全停转）
//     REPEAT=5 sh fan_minduty_sweep.sh 8            # 反复起停，看是否每次都起
//     HOLD=180 sh fan_minduty_sweep.sh 8            # 持续跑，看会不会跑着跑着停
// 三样都过了才能把一个新数字写进 DUTY_QUIET。
//  ② 超过 OT_ON（80°C）强制 100%，直到降回 OT_OFF（74°C）才解除。
//  ③ **SYSMON 迟迟读不到有效数据就强制 100%**。温度未知时唯一安全的假设
//     是"可能很热"。上电后 SYSMON 需要若干个采样周期才有第一个有效值，
//     这段时间里风扇是满速的 —— 听起来像出厂状态，几秒后自己降下来。
//  ④ **读数长时间一个比特都不变，也强制 100%。**
//     这一条是上板之后补的，因为第 ③ 条挡不住真实发生的那种坏法：
//     SYSMON 配置错了的时候，DRP **照样应答**，寄存器里**照样有一个看着
//     很合理的温度**（32.5°C），只是 ADC 根本没在转换。于是"读不到"永远
//     不成立，风扇心安理得停在最低档，而没有任何人会发现。
//     真实的结温永远在抖 —— 同期 PS 侧 AMS 的读数在 24.9~29.1°C 之间动，
//     而我这条链路五分钟六十次采样一个比特没变。所以"完全不变"本身就是
//     故障信号。误判的方向是风扇多吹，可以接受。
`default_nettype none

module fan_ctrl #(
    // PWM 周期：25 kHz 左右，避开人耳敏感区。75 MHz / 3000 = 25 kHz
    parameter integer PWM_PERIOD = 3000,
    // 多久没拿到有效温度就当故障（75 MHz 下约 0.9 秒）
    parameter integer STALE_LIMIT = 64_000_000,
    // 连续多少次采样读数**完全相同**就当传感器卡死（见文件头第 ④ 条）。
    // 单位是"采样次数"不是时钟拍数，这样换时钟频率不用重算 —— 采样间隔由
    // fan_sysmon 的 PERIOD 定（1 ms），30000 次 ≈ 30 秒。
    parameter integer STUCK_LIMIT = 30_000,
    // ============================================================================
    // 【阈值是参数，因为这块板热不起来】
    // ============================================================================
    // 默认值是真正要用的那一组（45/55/65/75°C 升，40/50/60/70 降，80 强制）。
    // 但**在这块板上没法用它做端到端验证**：实测把风扇完全停转、四个 CPU
    // 满载、PL 密码核循环跑，180 秒结温也只从 34.1 升到 36.5°C 就趋平 ——
    // 45°C 这一档在任何我能造出来的负载下都够不着。
    //
    // 所以阈值做成参数：另出一份**表征用**的 bitstream，把阈值压到这块板
    // 够得着的区间，就能在真硅上、用真传感器数据看到"温度上去→档位上去"
    // 这个上升沿。改的只有常数，控制律本身是同一份 RTL。
    //
    // ⚠️ 表征用的那份**不是产品形态**，跑完取完数就换回默认值。
    //
    // T0 是 2026-08 新加的「真·低温」档（见下面档位表）。它同时是把最低档
    // 降到 8% 的安全网：温度一过 T0_UP 就回到 25%，不必指望 8% 去救场。
    //
    // ⚠️ **这两个数是上板量出来的，不是按散热直觉拍的。**第一版拍的是
    //    30/35°C，上板一跑发现**一次都没进过安静档** —— 板子空载稳定在
    //    31.5~32.7°C，比我定的迟滞下界 30°C 还高，于是档 0 永远选不中，
    //    "低温更安静"这件事实际效果为零。
    //
    //    重量之后按真实工作区间定：
    //        风扇 8%  空载稳态  31.7~32.7°C   ← T0_DN 要高于它，留余量
    //        风扇 25% 空载稳态  31.5~32.1°C   （只差 0.5°C，见下）
    //        风扇 0%  四核满载  38.7°C 仍缓升 ← T0_UP 要低于它，才跨得过去
    //    所以 T0_DN=35（空载最高 32.7 之上留 2.3°C）、T0_UP=37（满载 38.7
    //    之下留 1.7°C）。这样两条性质在这块板上**才都成立**：空载真的进
    //    8% 安静档、满载真的升到 25%。迟滞 2°C 比其它档的 5°C 窄，是因为
    //    这块板可用的温度带总共才 6°C 宽。
    //
    //    顺带一个改变判断的实测：**8% 与 25% 的稳态温差只有约 0.5°C**。
    //    风扇在这块板上几乎不影响结温（散热由环境对流主导），也就是说
    //    多转 17 个百分点换不到 1°C —— 这反过来说明"让它安静转"是对的。
    parameter [15:0] T0_UP  = 16'd40504,  // 37°C
    parameter [15:0] T0_DN  = 16'd40243,  // 35°C
    parameter [15:0] T1_UP  = 16'd41547,  // 45°C
    parameter [15:0] T1_DN  = 16'd40895,  // 40°C
    parameter [15:0] T2_UP  = 16'd42850,  // 55°C
    parameter [15:0] T2_DN  = 16'd42198,  // 50°C
    parameter [15:0] T3_UP  = 16'd44153,  // 65°C
    parameter [15:0] T3_DN  = 16'd43501,  // 60°C
    parameter [15:0] T4_UP  = 16'd45456,  // 75°C
    parameter [15:0] T4_DN  = 16'd44804,  // 70°C
    parameter [15:0] OT_ON  = 16'd46108,  // 80°C 强制全速
    parameter [15:0] OT_OFF = 16'd45326   // 74°C 解除
) (
    input  wire        clk,
    input  wire        rst_n,

    // ---- 温度输入（来自 fan_sysmon）----
    input  wire [15:0] temp_code,      // SYSMON 的 16 位温度码
    input  wire        temp_valid,     // 每次更新拉一拍

    // ---- 观测/覆盖（来自 AXI，可选）----
    input  wire        ovr_en,         // 1 = 用 ovr_duty 代替自动档位
    input  wire [7:0]  ovr_duty,       // 0..100
    output wire [15:0] cur_temp,       // 最近一次温度码
    output wire [7:0]  cur_duty,       // 当前占空比（百分比）
    output wire [2:0]  cur_step,       // 当前档位 0..5
    output wire        forced_full,    // 因高温 / 数据陈旧 / 传感器卡死被强制满速
    output wire        sensor_stuck,   // 读数长时间一个比特不变

    // ---- 出到 AA11 ----
    output wire        fan_pin
);
    // 温度阈值现在是参数（见上面那段注释）。换算方式见文件头：
    //   code = (T + 273.8195117) × 65536 / 502.9098127
    // 改档位请改摄氏度再重算，别直接改数字。

    // ================= 档位对应的占空比 =================
    // 0 档是**保底转速**不是停转，理由见文件头第 ① 条。
    //
    //   档 0  <37°C   8%   安静档（实测自启动下限 6%，见文件头）
    //   档 1  37~45   25%  原来的最低档，现在成了 8% 的安全网
    //   档 2  45~55   40%
    //   档 3  55~65   60%
    //   档 4  65~75   80%
    //   档 5  >75     100%
    //
    // 【原来最低档一路管到 45°C，而这块板满载都到不了 45°C】
    // 也就是说风扇**从来没升过档**，"温度升就提速"这条在这块板上一次都没被
    // 真正执行过。加 T0 这一档就是为了让它可观测。
    //
    // ⚠️ 但**第一版的 30/35°C 没做到**：上板实测板子空载就有 31.5~32.7°C，
    //    比迟滞下界 30°C 还高，于是档 0 永远选不中 —— 改了等于没改。
    //    而且风扇转着的时候四核满载只到 32.4°C 就趋平，35°C 也跨不过去。
    //    按实测重定成 35/37 之后两头才都够得着（推导见上面 T0_UP/T0_DN）。
    //    教训：**阈值必须落在这块板的真实温度带里**，按通用散热直觉拍的数
    //    会安静地什么都不做 —— 仿真全绿、上板无效。
    localparam [7:0] DUTY_QUIET = 8'd8;
    localparam [7:0] DUTY_MIN   = 8'd25;
    localparam [7:0] DUTY_1     = 8'd40;
    localparam [7:0] DUTY_2     = 8'd60;
    localparam [7:0] DUTY_3     = 8'd80;
    localparam [7:0] DUTY_4     = 8'd100;

    // ================= 迟滞档位机 =================
    reg  [2:0]  step;
    reg  [15:0] temp_r;
    reg         ot_latch;
    reg  [25:0] stale;          // 距上次有效温度多久
    wire        stale_bad = (stale >= STALE_LIMIT[25:0]);
    reg  [15:0] same_cnt;       // 连续多少次采样读数完全相同
    wire        stuck_bad = (same_cnt >= STUCK_LIMIT[15:0]);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            step     <= 3'd5;       // 上电先满速，等第一个温度再降 —— 见第 ③ 条
                                    // （这也保证了风扇在进入 8% 之前必定已经转起来）
            temp_r   <= 16'd0;
            ot_latch <= 1'b1;
            stale    <= {26{1'b1}};
            same_cnt <= 16'd0;
        end else begin
            if (temp_valid) begin
                temp_r <= temp_code;
                stale  <= 26'd0;

                // 卡死检测：一模一样就累加，变了就清零。到顶不再加，
                // 否则会绕回 0 把故障状态自己"治好"。
                if (temp_code == temp_r) begin
                    if (!stuck_bad) same_cnt <= same_cnt + 16'd1;
                end else begin
                    same_cnt <= 16'd0;
                end

                // 过温锁存：进得早、出得晚
                if (temp_code >= OT_ON)       ot_latch <= 1'b1;
                else if (temp_code <= OT_OFF) ot_latch <= 1'b0;

                // 一次只升/降一档：温度是慢变量，跳档没有意义，
                // 而逐档走能让"档位"这个状态本身有可读性
                if (step < 3'd5 && temp_code >= (step == 3'd0 ? T0_UP :
                                                 step == 3'd1 ? T1_UP :
                                                 step == 3'd2 ? T2_UP :
                                                 step == 3'd3 ? T3_UP : T4_UP))
                    step <= step + 3'd1;
                else if (step > 3'd0 && temp_code <= (step == 3'd1 ? T0_DN :
                                                      step == 3'd2 ? T1_DN :
                                                      step == 3'd3 ? T2_DN :
                                                      step == 3'd4 ? T3_DN : T4_DN))
                    step <= step - 3'd1;
            end else if (!stale_bad) begin
                stale <= stale + 26'd1;
            end
        end
    end

    // ================= 占空比选择 =================
    wire [7:0] auto_duty = (step == 3'd0) ? DUTY_QUIET :
                           (step == 3'd1) ? DUTY_MIN   :
                           (step == 3'd2) ? DUTY_1     :
                           (step == 3'd3) ? DUTY_2     :
                           (step == 3'd4) ? DUTY_3     : DUTY_4;

    // 强制满速优先于一切，包括手动覆盖 —— 覆盖是给调试用的，
    // 不能让调试的人把芯片烤了。
    wire force_full = ot_latch || stale_bad || stuck_bad;
    wire [7:0] duty = force_full ? 8'd100
                    : ovr_en     ? ((ovr_duty > 8'd100) ? 8'd100 : ovr_duty)
                                 : auto_duty;

    // ================= PWM =================
    // 阈值 = 周期 × duty / 100。周期是参数、duty 最大 100，
    // 乘法结果最宽 3000×100 = 300000，20 位够。
    reg  [31:0] pwm_cnt;
    wire [31:0] thresh = (PWM_PERIOD * duty) / 32'd100;
    wire        pwm_on = (pwm_cnt < thresh);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)                              pwm_cnt <= 32'd0;
        else if (pwm_cnt + 32'd1 >= PWM_PERIOD)  pwm_cnt <= 32'd0;
        else                                     pwm_cnt <= pwm_cnt + 32'd1;
    end

    // ⚠️ 唯一一处反相：AA11 低=转。别在别处再反。
    assign fan_pin = ~pwm_on;

    assign cur_temp    = temp_r;
    assign cur_duty    = duty;
    assign cur_step    = step;
    assign forced_full  = force_full;
    assign sensor_stuck = stuck_bad;

endmodule

`default_nettype wire
