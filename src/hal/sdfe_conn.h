/* sdfe_conn —— 到密码机服务的**唯一一条**连接
 *
 * ============================================================================
 * 【为什么必须共用，而不是各开各的】
 * ============================================================================
 * pqchsm_fpgad 是单线程的，而且**一次只服务一个连接**（accept 之后一直读到
 * 对端关闭才回去 accept）—— 这不是偷懒，是因为三个密码核都是有状态的序列，
 * 两个客户端交错驱动会得到互相错位但看起来完全合法的结果。
 *
 * 于是"熵源开一条、算法后端再开一条"这种写法必然出事：第二条连接卡在监听
 * 队列里，第一条空闲 10 秒被服务端超时关掉，另一条才轮上。表现是熵源取不到
 * 随机数，而 liboqs 的 RNG 回调签名是 void、没法报错，只能 abort()。
 *
 * 实测就是这样：两个开关**单独用都 254/254 全过，一起用就 SIGABRT**，
 * 而且崩在任何输出之前，看不出跟连接有关。
 *
 * 所以进程内只留一条连接，两个消费者共用。加锁是因为它们可能在不同线程里
 * 被调到，而共用连接上的请求-响应必须成对，不能交错。
 */
#ifndef PQCHSM_SDFE_CONN_H
#define PQCHSM_SDFE_CONN_H

#include "sdfe.h"

/* 取共享会话。第一次调用时按环境变量连（本机 socket 或 TCP）。
 * 返回 NULL 表示连不上 —— 调用方必须如实失败，不许回退。 */
SDFE_HANDLE sdfe_conn_get(void);

/* 连接坏了就丢掉，下次 get 会重连。**本次仍然要报失败** ——
 * 悄悄重试会把一次真实的硬件故障掩盖成偶发延迟。 */
void sdfe_conn_drop(void);

/* 共享连接上的一次请求必须整体互斥：请求与响应成对，不能被另一个
 * 消费者插进来。调用方在一次完整往返前后加锁。 */
void sdfe_conn_lock(void);
void sdfe_conn_unlock(void);

#endif
